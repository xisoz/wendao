## 二、紫微斗数

**《紫微斗数全书》**　旧题宋代陈希夷（陈抟）撰，现存多为明清刊本，一般认为是明代以后整理成书。内容包括安星法、星曜性质、诸宫论断与歌赋，是紫微斗数最主要的传统文献。

## 三、六爻（纳甲筮法）

**《火珠林》**　旧题麻衣道者撰，大约宋代以前已流传。现存最早的纳甲筮法专书之一，“以钱代蓍”的起卦法一般溯源于此，论述以世应、六亲、用神为主。

**《增删卜易》**　清初野鹤老人原著，李文辉（号觉子）增删整理，成书于康熙年间。书中大量引用作者亲历的占例，主张以实验去伪存真，删除不验的旧说，在六爻学习者中影响很大。

**《卜筮正宗》**　清代王洪绪（王维德）著，成书于乾隆年间。以注解明代《黄金策》为主体，并辨正前人谬误，是与《增删卜易》并称的六爻要籍。

