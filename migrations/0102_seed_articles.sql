|---|---|---|---|
| 一背二字 | 单（少阳） | 阳爻，静 | — |
| 二背一字 | 拆（少阴） | 阴爻，静 | — |
| 三背 | 重（老阳） | 阳爻，动 | ○ |
| 三字 | 交（老阴） | 阴爻，动 | × |

“老”则变：老阳变阴，老阴变阳。所得为**本卦**，动爻变后为**变卦**（又称之卦）。正反的记法各家不一，起卦前约定好即可。

## 二、八宫与世应

京房把六十四卦分为乾、坎、艮、震、巽、离、坤、兑八宫，每宫八卦。以乾宫为例：

乾为天（本宫，世上爻）→ 天风姤（一世）→ 天山遁（二世）→ 天地否（三世）→ 风地观（四世）→ 山地剥（五世）→ 火地晋（游魂，世四爻）→ 火天大有（归魂，世三爻）。

**世爻**代表问卦者自身，**应爻**代表对方或所问之事，世应相隔两爻（世初应四、世二应五、世三应上）。

## 三、纳甲

把天干地支“纳”入各爻。内卦（初、二、三爻）与外卦（四、五、上爻）各有配法，例如：

- 乾：内卦甲子、甲寅、甲辰；外卦壬午、壬申、壬戌；
- 坤：内卦乙未、乙巳、乙卯；外卦癸丑、癸亥、癸酉。

地支即决定该爻的五行。

## 四、六亲

以本卦所在**宫的五行**为“我”，对照各爻五行：

- 同我者为兄弟；我生者为子孙；我克者为妻财；克我者为官鬼；生我者为父母。

如乾宫属金，乾为天初爻子水为金所生，故为子孙。变卦各爻的六亲，仍以本卦之宫论。

## 五、日辰、月建与旬空

断卦时以起卦当日的**日辰**和当月的**月建**（以节气换月）衡量各爻旺衰：与日月同五行或得其生者为旺，被克者为衰。日辰所在旬中缺失的两个地支称为**旬空**（空亡）。

## 六、用神与动变

依所问之事取对应六亲为“用神”：问工作看官鬼，问财看妻财，问文书看父母等。再看用神旺衰、是否发动、动后变出何爻（回头生克），以及与世爻的关系。这一部分流派差异较大，《增删卜易》《卜筮正宗》都有系统论述。

问道公众号回复“六爻 所问之事”可模拟一次钱式起卦，自动装好纳甲、六亲、世应与动变，供学习对照。

