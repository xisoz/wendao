**《滴天髓》**　旧题宋代京图撰、明代刘基（刘伯温）注，成书年代与作者均有争议。全书以韵文写成，文字简约，偏重理气、旺衰与通变，被视为命理学的纲领性著作。清代任铁樵的《滴天髓阐微》、民国徐乐吾的《滴天髓补注》是常见的注本。

