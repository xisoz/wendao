TONE_CHARS = {
    "ā": ("a", 1), "á": ("a", 2), "ǎ": ("a", 3), "à": ("a", 4),
    "ē": ("e", 1), "é": ("e", 2), "ě": ("e", 3), "è": ("e", 4),
    "ī": ("i", 1), "í": ("i", 2), "ǐ": ("i", 3), "ì": ("i", 4),
    "ō": ("o", 1), "ó": ("o", 2), "ǒ": ("o", 3), "ò": ("o", 4),
    "ū": ("u", 1), "ú": ("u", 2), "ǔ": ("u", 3), "ù": ("u", 4),
    "ǖ": ("v", 1), "ǘ": ("v", 2), "ǚ": ("v", 3), "ǜ": ("v", 4),
    "ü": ("v", 0),
}

def split_py(marked: str):
    raw = marked.strip().split(",")[0].split("/")[0]
    tone = 0
    out = []
    for ch in raw:
        if ch in TONE_CHARS:
            base, t = TONE_CHARS[ch]
            out.append(base)
            if t:
                tone = t
        else:
            out.append(ch)
    py = "".join(out).replace("ü", "v")
    if tone == 0:
        tone = 1
    return py, tone

def load_kangxi():
    text = KANGXI.read_text(encoding="utf-8-sig")
    lines = text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("CodePoint"))
    m = {}
    for row in csv.DictReader(io.StringIO("\n".join(lines[start:]))):
        m[row["Character"]] = int(row["Strokes"])
    return m

